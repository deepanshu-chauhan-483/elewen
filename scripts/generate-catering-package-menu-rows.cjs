#!/usr/bin/env node
'use strict';

/**
 * Generate frontend/src/lib/cateringPackageMenuRows.js from Strapi catering seeds.
 * Run from repo root: node scripts/generate-catering-package-menu-rows.cjs
 */
const fs = require('node:fs');
const path = require('node:path');

const { ESSENTIAL_PACKAGES } = require('../strapi/src/seed/catering-essentials');
const { ASSISTED_PACKAGES } = require('../strapi/src/seed/catering-assisted');
const { END_TO_END_PACKAGES } = require('../strapi/src/seed/catering-end-to-end');

const bySlug = {};

for (const pkg of [...ESSENTIAL_PACKAGES, ...ASSISTED_PACKAGES, ...END_TO_END_PACKAGES]) {
  if (Array.isArray(pkg.menu_items) && pkg.menu_items.length) {
    bySlug[pkg.slug] = pkg.menu_items;
  }
}

const outPath = path.resolve(__dirname, '../frontend/src/lib/cateringPackageMenuRows.js');
const contents = `/** Package menu_items rows from Strapi seeds — used when CMS menu_items are missing or invalid. */
/** Generated by scripts/generate-catering-package-menu-rows.cjs — do not edit by hand. */
export const CATERING_PACKAGE_MENU_ROWS = ${JSON.stringify(bySlug, null, 2)}
`;

fs.writeFileSync(outPath, contents, 'utf8');
console.log(
  `[generate-catering-package-menu-rows] wrote ${Object.keys(bySlug).length} packages → ${outPath}`
);
