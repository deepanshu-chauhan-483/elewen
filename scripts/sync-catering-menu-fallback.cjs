#!/usr/bin/env node
'use strict';

/**
 * Regenerate frontend/src/lib/cateringMenuFallback.js from strapi seed data.
 * Run from repo root: node scripts/sync-catering-menu-fallback.cjs
 */
const fs = require('node:fs');
const path = require('node:path');

const { CATERING_MENU_CATEGORIES } = require('../strapi/src/seed/catering-menu-data');

const byKey = {};
let total = 0;

for (const category of CATERING_MENU_CATEGORIES) {
  byKey[category.category_key] = category.dishes.map(dish => ({
    name: dish.name,
    ...(dish.description ? { description: dish.description } : {}),
    dietary: dish.dietary,
    sort_order: dish.sort_order,
    level_1: dish.level_1 !== false,
    level_2: dish.level_2 !== false,
    level_3: dish.level_3 !== false,
  }));
  total += category.dishes.length;
}

const outPath = path.resolve(__dirname, '../frontend/src/lib/cateringMenuFallback.js');
const contents = `/** Offline fallback when Strapi catering-menu is unavailable (mirrors strapi seed). */
/** Generated by scripts/sync-catering-menu-fallback.cjs — do not edit by hand. */
export const CATERING_MENU_FALLBACK = ${JSON.stringify(byKey, null, 2)
  .replace(/"([^"]+)":/g, '$1:')
  .replace(/"description":/g, 'description:')
  .replace(/"dietary":/g, 'dietary:')
  .replace(/"sort_order":/g, 'sort_order:')
  .replace(/"name":/g, 'name:')}
`;

// Keep quoted strings for name/description/dietary values
const fixed = `/** Offline fallback when Strapi catering-menu is unavailable (mirrors strapi seed). */
/** Generated by scripts/sync-catering-menu-fallback.cjs — do not edit by hand. */
export const CATERING_MENU_FALLBACK = ${JSON.stringify(byKey, null, 2)}
`;

fs.writeFileSync(outPath, fixed, 'utf8');
console.log(`[sync-catering-menu-fallback] wrote ${total} dishes across ${Object.keys(byKey).length} categories → ${outPath}`);
